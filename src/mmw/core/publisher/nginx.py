"""Generate a conf.d-style nginx configuration for a published mirror.

Name-based virtual hosting: the network mounts at /srv/mmw inside nginx.
The publish layout mirrors the upstream URL hierarchy exactly, so a DNS-spoofed
`archive.ubuntu.com` lands on `/srv/mmw/archive.ubuntu.com/` and the URL path
continues underneath unchanged.

**Hostnames derive from the network's own mirrors, never a constant.** The
dist-upgrade DNS table had to learn this the hard way: it named
archive.ubuntu.com and security.ubuntu.com unconditionally, so an arm64 network
— which mirrors ports.ubuntu.com and neither of those — was told to point DNS
at two hostnames it had no copy of.
"""
import re
from urllib.parse import urlparse

from mmw.core.config import MirrorConfig

ROOT_PLACEHOLDER = "__MMW_ROOT__"

_SITE = """\
server {{
    listen 80;
{tls}    server_name {server_name};

    root {root}/{host};
    autoindex on;
    autoindex_exact_size off;

    # apt fetches many small index files; sendfile avoids a userspace copy
    # by handing the read/write off to the kernel.
    sendfile on;
    tcp_nopush on;

    location / {{
        try_files $uri $uri/ =404;
    }}

    # This network's repository signing keys ({root}/keys/{{label}}/, both
    # encodings), so a client can fetch one from whichever host it already
    # resolves to the mirror. A path mmw reserves, not an upstream one.
    location /mmw-keys/ {{
        alias {root}/keys/;
    }}
}}
"""

_TLS = """\
    listen 443 ssl;
    ssl_certificate {cert};
    ssl_certificate_key {key};
"""

# One file, every server block inline. This used to be a `mirror.conf` that
# included `sites/*.conf` beside it — and Debian's stock nginx.conf loads
# `sites-enabled/*`, which matches a `sites/` subdirectory too: copying the
# generated folder there stopped nginx from starting at all ("is a
# directory"). A single file works wherever it is dropped or symlinked.
_MAIN = """\
# Generated by mmw — do not edit; regenerated on every publish and bundle.
#
# Used by nginx/compose.yaml. The network folder is mounted at {root}
# and its nginx/ directory at /etc/nginx/conf.d, both read-only.
# Edit the host-side Compose mount sources; keep container paths unchanged.
#
# Point DNS for each hostname below at this server.
#
# Hosts served by this mirror:
{hosts}
{tls_note}
{sites}"""


_SITE_BLOCK = """\
server {{
    listen 80;
{tls}    server_name {server_name};
{body}}}
"""

_STATIC_BODY = """
    root {root}/{dir};
    autoindex on;
    autoindex_exact_size off;
    sendfile on;
    tcp_nopush on;

    location / {{
        try_files $uri $uri/ =404;
    }}
"""

# `add_header` inside `if` replaces the location's, so the preflight answer
# carries its own copy of the origin header.
_CORS_STATIC_BODY = """
    root {root}/{dir};
    autoindex on;
    autoindex_exact_size off;
    sendfile on;
    tcp_nopush on;

    location / {{
        if ($request_method = OPTIONS) {{
            add_header Access-Control-Allow-Origin "*" always;
            add_header Access-Control-Allow-Methods "GET, HEAD, OPTIONS" always;
            add_header Access-Control-Allow-Headers "$http_access_control_request_headers" always;
            add_header Access-Control-Max-Age 86400 always;
            return 204;
        }}
        add_header Access-Control-Allow-Origin "*" always;
        try_files $uri $uri/ =404;
    }}
"""

_PROXY_BODY = """
    location {eq}{path} {{
        proxy_pass http://{proxy_host}:{port};
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-Proto $scheme;
    }}
"""


# PEP 691: a client asking for the JSON type gets index.json, anyone else the
# PEP 503 HTML. Emitted once, at http level, when any site negotiates.
_SIMPLE_MAP = """\
map $http_accept $pypi_simple_index {
    default index.html;
    "~application/vnd\\.pypi\\.simple\\.v1\\+json" index.json;
}
"""

_NEGOTIATED_BODY = """
    location {prefix} {{
        types {{
            application/vnd.pypi.simple.v1+json json;
            text/html html;
        }}
        try_files $uri$pypi_simple_index $uri/$pypi_simple_index $uri =404;
    }}
"""

_JSON_BODY = """
    location {prefix} {{
        types {{ }}
        default_type application/json;
        try_files $uri =404;
    }}
"""


def _render_site(site, root: str, tls_block: str, port: int, proxy_host: str) -> str:
    body = ""
    if site.root is not None:
        body += (_CORS_STATIC_BODY if site.cors else _STATIC_BODY).format(root=root, dir=site.root)
    if site.negotiated_index:
        body += _NEGOTIATED_BODY.format(prefix=site.negotiated_index)
    if site.json_paths:
        body += _JSON_BODY.format(prefix=site.json_paths)
    for path in site.proxy:
        body += _PROXY_BODY.format(eq="= " if site.exact else "", path=path, port=port, proxy_host=proxy_host)
    for path in site.proxy_prefixes:
        body += _PROXY_BODY.format(eq="", path=path, port=port, proxy_host=proxy_host)
    if site.root is None and "/" not in site.proxy:
        body += "\n    location / {\n        return 404;\n    }\n"
    return _SITE_BLOCK.format(tls=tls_block, server_name=site.server_name, body=body)


_WILDCARD_RE = re.compile(r"^~\^\[\^\.\]\+\\\.(.+)\$$")


def _dns_name(server_name: str) -> str:
    r"""What DNS needs for a server_name: `~^[^.]+\.example\.com$` (the regex
    a provider writes for one label of wildcard) reads `*.example.com`."""
    m = _WILDCARD_RE.match(server_name)
    return "*." + m.group(1).replace("\\.", ".") if m else server_name


def split_for_nginx(units) -> tuple[list, list]:
    """(units served by a static block per `mirror_base`, provider `Site`s)."""
    from mmw.providers import all_providers, get_provider
    static = [u for u in units if get_provider(u.provider).site_per_base]
    sites = []
    for provider in all_providers():
        mine = [u for u in units if u.provider == provider.name]
        if mine:
            sites.extend(provider.nginx_sites(mine))
    return static, sites


def hostnames(mirrors: list[MirrorConfig]) -> list[str]:
    """Distinct *directory* names this network serves, from its own mirrors —
    `mirror_base`'s first path segment, which is also what `root {root}/{h}`
    must point at to match the published layout on disk.

    This is deliberately NOT what a client's Host header says: a
    non-standard port is mangled to `{host}_{port}` here (see
    `MirrorConfig.mirror_base`) so two repos on the same host at different
    ports don't collide on disk. `_server_names()` below derives the real
    hostname for the `server_name` directive, which must never contain that
    mangled form — see `test_non_standard_port_host_uses_real_hostname_for_server_name`.
    """
    seen: list[str] = []
    for m in mirrors:
        host = m.mirror_base.split("/", 1)[0]
        if host and host not in seen:
            seen.append(host)
    return sorted(seen)


def _server_names(mirrors: list[MirrorConfig]) -> dict[str, str]:
    """dir-name (as `hostnames()` returns) -> the real DNS hostname a client
    actually sends as `Host:`.

    Found: for a non-standard port, `hostnames()`'s mangled `{host}_{port}`
    form was used verbatim as `server_name` too — `server_name
    archive.example.com_8080;` matches no request nginx will ever receive.
    The `root` path is correct as-is (it must match the mangled on-disk
    directory); only `server_name` needed the unmangled host.
    """
    mapping: dict[str, str] = {}
    for m in mirrors:
        dir_name = m.mirror_base.split("/", 1)[0]
        if dir_name and dir_name not in mapping:
            mapping[dir_name] = urlparse(m.source_url).hostname or dir_name
    return mapping


def nginx_files(mirrors: list[MirrorConfig], root: str, *,
                tls: tuple[str, str] | None = None,
                tls_include: str | None = None,
                extra_hosts: list[str] | tuple[str, ...] = (),
                sites=(), port: int = 8765, proxy_host: str = "127.0.0.1") -> dict[str, bytes]:
    """Sink-relative path → file content (always exactly `nginx/mirror.conf`).

    `root` is the absolute directory the tree lives in. Pass ROOT_PLACEHOLDER
    when the destination is not known until apply time (bundles).

    `tls` is `(certificate, key)` paths; when given, every server block also
    listens on 443 with them. Plain HTTP stays on either way — a client whose
    sources say `http://` must keep working.

    `tls_include` (a bundle's far side, whose certificate is signed there):
    every server block includes this wildcard path instead. nginx ignores a
    wildcard include that matches nothing, so the config loads before any
    certificate exists; apply.py writes the matching file — `listen 443 ssl`
    and the certificate paths — once a signed certificate fits the key.

    `extra_hosts` are directories published beside the mirrors that are also
    their own hostname — `changelogs.ubuntu.com` for a `dist_upgrade` network,
    which no mirror's URL names.

    `sites` are provider-declared blocks (`providers.base.Site`) rendered
    after the per-host ones, proxying to `proxy_host`:`port`.
    """
    provider_sites = list(sites)
    server_names = _server_names(mirrors)
    for h in extra_hosts:
        # A directory name, mangled `host_port` for a non-standard port
        # exactly as `hostnames()` documents; server_name wants the host.
        head, sep, tail = h.rpartition("_")
        server_names.setdefault(h, head if sep and tail.isdigit() else h)
    hosts = sorted(set(hostnames(mirrors)) | set(extra_hosts))
    tls_block = (_TLS.format(cert=tls[0], key=tls[1]) if tls
                 else f"    include {tls_include};\n" if tls_include else "")
    sites = "\n".join(
        _SITE.format(host=host, root=root, server_name=server_names.get(host, host),
                     tls=tls_block)
        for host in hosts
    )
    if provider_sites:
        rendered = "\n".join(_render_site(s, root, tls_block, port, proxy_host) for s in provider_sites)
        if any(s.negotiated_index for s in provider_sites):
            rendered = f"{_SIMPLE_MAP}\n{rendered}"
        sites = f"{sites}\n{rendered}" if sites else rendered
        hosts = hosts + [_dns_name(s.server_name) for s in provider_sites]
    tls_note = ("#\n# HTTPS: every host also listens on 443 with\n"
                f"#   {tls[0]}\n") if tls else (
        "#\n# HTTPS: on once a signed certificate is installed — apply.py then\n"
        f"# writes {tls_include.replace('*', '')}\n") if tls_include else ""
    return {
        "nginx/mirror.conf": _MAIN.format(
            root=root,
            hosts="\n".join(f"#   {h}" for h in hosts) or "#   (none)",
            tls_note=tls_note,
            sites=sites,
        ).encode()
    }


def deployment_nginx_files(mirrors, *, network_name: str,
                           tls_include=None, **kwargs) -> dict[str, bytes]:
    """The generated config always serves the fixed container mount."""
    from mmw.core.publisher.nginx_container import CONTAINER_ROOT, deployment_files
    container_include = f"{CONTAINER_ROOT}/.mmw/tls/https*.conf" if tls_include else None
    with_gallery = any(site.proxy or site.proxy_prefixes for site in kwargs.get("sites", ()))
    if with_gallery:
        from mmw.core.publisher.nginx_container import GALLERY_HOST, GALLERY_PORT
        kwargs.update(proxy_host=GALLERY_HOST, port=GALLERY_PORT)
    files = nginx_files(mirrors, CONTAINER_ROOT,
                        tls_include=container_include, **kwargs)
    files.update(deployment_files(network_name, with_gallery=with_gallery))
    return files


def recorded_nginx_files(settings: str, root: str, *,
                         tls: tuple[str, str] | None = None,
                         tls_include: str | None = None, legacy: bool = False) -> dict[str, bytes]:
    """Container setup regenerated from snapshot settings; empty with nginx off.

    `legacy` is only for reconstructing the previous manifest of a bundle
    made before container configs, so an upgrade delta resends its config.
    """
    import json

    from mmw.core.certs import CHANGELOGS_HOST
    recorded = json.loads(settings or "{}")
    rec_net = recorded.get("network", {})
    if not rec_net.get("nginx", True):
        return {}
    mirrors = [MirrorConfig.model_validate(m) for m in recorded.get("mirrors", [])]
    mirrors, sites = split_for_nginx(mirrors)
    extra = list(recorded.get("upstream_hosts", []))
    if "extra_hosts" in recorded:
        extra += [h for h in recorded["extra_hosts"] if h not in extra]
    elif rec_net.get("dist_upgrade"):
        # Recorded before providers named their extra hosts.
        extra.append(CHANGELOGS_HOST)
    if legacy:
        # Those bundles proxied a standalone gallery on its host port.
        return nginx_files(mirrors, root, tls=tls, tls_include=tls_include, extra_hosts=extra,
                           sites=sites, port=rec_net.get("gallery_port", 8765))
    return deployment_nginx_files(mirrors, network_name=rec_net.get("name", "network"),
                                  tls_include=tls_include, extra_hosts=extra, sites=sites)
