"""Offline nginx image and Compose setup for each published network."""
import json
import re
from pathlib import Path

from mmw.core import disk_io
from mmw.core.container_image import ImageResult, container_image
from mmw.core.pool import KIND_PKG
from mmw.core.publisher.results import MirrorPublishResult

DOCKER = "docker"
IMAGE = "nginx:latest"
PLATFORM = "linux/amd64"
TAR_NAME = "nginx-latest-linux-amd64.tar"
CACHE = "nginx-image"
CONTAINER_ROOT = "/srv/mmw"
TLS_INCLUDE = f"{CONTAINER_ROOT}/.mmw/tls/https*.conf"
GALLERY_HOST = "gallery"    # the VS Code gallery service, inside the Compose network
GALLERY_PORT = 8080


def nginx_image(cache: Path, *, progress=None, stop_event=None) -> ImageResult:
    return container_image(cache, image=IMAGE, platform=PLATFORM, docker=DOCKER,
                           label="Nginx", progress=progress, stop_event=stop_event)


def publish_image(mirror_dir, sink, result, *, progress=None, stop_event=None) -> set[str]:
    image = nginx_image(
        mirror_dir / CACHE, stop_event=stop_event,
        progress=(lambda phase: progress("nginx", f"nginx-image:{phase}")) if progress else None,
    )
    if stop_event is not None and stop_event.is_set():
        return set()
    result.warnings.extend(image.notes)
    if image.path is None:
        result.warnings.append(
            f"{image.error} — the nginx image is not included; load {IMAGE} ({PLATFORM}) "
            "on the serving host some other way"
        )
        return set()
    rel = f"nginx/{TAR_NAME}"
    before = len(sink.errors)
    if sink.link(image.path, rel, disk_io.ops.stat(image.path).st_size, image.checksum, KIND_PKG) == "error":
        result.mirrors.append(MirrorPublishResult(
            mirror_name="nginx image", errors=sink.errors[before:] or [f"could not publish {rel}"],
        ))
        return set()
    return {rel}


def deployment_files(name: str, *, with_gallery: bool = False) -> dict[str, bytes]:
    """Fixed container paths, with explicit host-side source placeholders."""
    source = f"/path/to/{name}"
    slug = re.sub(r"[^a-z0-9_-]+", "-", name.lower()).strip("-_") or "network"

    def mount(host, target):
        return f"      - {json.dumps(f'{host}:{target}:ro')}\n"

    mounts = mount(source, CONTAINER_ROOT) + mount(f"{source}/nginx", "/etc/nginx/conf.d")
    depends = ""
    gallery = ""
    gallery_setup = ""
    gallery_note = ""
    if with_gallery:
        from mmw.providers.vscode.image import IMAGE as GALLERY_IMAGE, TAR_NAME as GALLERY_TAR
        depends = "    depends_on:\n      gallery:\n        condition: service_healthy\n"
        gallery = f"""\
  gallery:
    image: {GALLERY_IMAGE}
    platform: {PLATFORM}
    pull_policy: never
    command: ["python", "/data/gallery.py", "--data", "/data", "--port", "{GALLERY_PORT}"]
    restart: unless-stopped
    volumes:
{mount(f"{source}/vscode-gallery", "/data")}    healthcheck:
      test: ["CMD", "python", "-c", "import urllib.request; urllib.request.urlopen('http://127.0.0.1:{GALLERY_PORT}/healthz')"]
      interval: 30s
      timeout: 5s
"""
        gallery_setup = f"docker load -i ../vscode-gallery/{GALLERY_TAR}\n"
        gallery_note = (f"The VS Code gallery runs in this same Compose stack. Its port\n"
                        f"{GALLERY_PORT} is internal; nginx reaches it at "
                        f"`{GALLERY_HOST}:{GALLERY_PORT}`.\n")
    compose = f"""\
# Generated by mmw. Replace the host-side /path/to/{name} mount sources.
# Container paths are fixed; /path/to/{name} is the host source placeholder.
# Load the included image first; this setup never pulls on the serving host.
name: mmw-nginx-{slug}
services:
  nginx:
    image: {IMAGE}
    platform: {PLATFORM}
    pull_policy: never
    ports:
      - "80:80"
      - "443:443"
    restart: unless-stopped
{depends}    volumes:
{mounts}{gallery}"""
    readme = f"""\
# Serve network {name} with nginx

This directory contains the official `{IMAGE}` image for `{PLATFORM}`,
`compose.yaml`, and the generated `mirror.conf` it mounts.

The repository always mounts at `{CONTAINER_ROOT}` inside the container.
Replace the host-side `/path/to/{name}` placeholders in the bind mounts
with the actual network folder; leave container paths unchanged.
Keep your edited deployment copy outside the published folder so later
publishes do not overwrite it and bundle manifest verification still passes.
Published trees can be copied directly to a drive. They include `apply.py`,
plus `sign.py` and private `.mmw/tls/` assets when TLS is enabled.
For a bundle, run `apply.py` first. Then, from this directory on the Linux
serving host:

```sh
docker load -i {TAR_NAME}
{gallery_setup}cp compose.yaml /path/to/{name}-compose.yaml
# Edit the host paths in that deployment copy, then:
docker compose -f /path/to/{name}-compose.yaml config
docker compose -f /path/to/{name}-compose.yaml run --rm nginx nginx -t
docker compose -f /path/to/{name}-compose.yaml up -d --force-recreate
```

The repository and `nginx/` directory mounts are read-only. TLS in both publish and bundle deployments
lives under the network folder's `.mmw/tls`: `apply.py` enables HTTPS once
the signed certificate fits its key. After signing on the far side, run
`apply.py --tls --root /actual/path/to/{name}`, then recreate the container.
Clients must trust the signing CA.

If no image tar was included (publish warned that Docker and its cache were
unavailable), load `{IMAGE}` for `{PLATFORM}` separately before starting.
Compose never tries to pull it from an offline registry.

Compose uses bridge networking with host port mappings `80:80` and `443:443`.
Change the left side to use other host ports, for example `8080:80` and
`8443:443`; keep container ports 80 and 443 unchanged. Clients must use those
chosen ports. HTTPS requires the signed certificate setup above.
{gallery_note}Point clients' DNS at this host.

After another publish or bundle apply, load a changed image and recreate the
container using your deployment copy. Compare newly generated Compose files
for setup changes before updating that copy. Image bytes travel
in delta bundles only when they change. `nginx = false` omits this setup.
"""
    return {"nginx/compose.yaml": compose.encode(), "nginx/README.md": readme.encode()}
